def classify_google_ads_campaign(name: str) -> Dict[str, str]:
    """Classifies a Google Ads campaign name into a vertical and short code."""
    n_upper = (name or "").upper()
    if "CONTRACTOR" in n_upper or "ROOFING" in n_upper or "HVAC" in n_upper or "TRADES" in n_upper or "HOME SERVICE" in n_upper:
        return {
            "vertical": "CT Contractors & Trades",
            "short_code": "BOFU_CT_CONTRACTORS",
            "funnel_stage": "BOFU" if "BOFU" in n_upper else "MOFU",
        }
    if "CT LOCAL" in n_upper or "GENERAL SERVICES" in n_upper or "CT " in n_upper or "CONNECTICUT" in n_upper:
        return {
            "vertical": "CT Local General Services",
            "short_code": "BOFU_CT_GENERAL",
            "funnel_stage": "BOFU" if "BOFU" in n_upper else "MOFU",
        }
    if "GREENFIELD" in n_upper or "SPRINT" in n_upper or "INTERNAL TOOLS" in n_upper or "ENTERPRISE" in n_upper:
        return {
            "vertical": "Enterprise Greenfield",
            "short_code": "BOFU_GREENFIELD",
            "funnel_stage": "BOFU" if "BOFU" in n_upper else "MOFU",
        }
    return {
        "vertical": "Core Commercial",
        "short_code": "BOFU_CORE" if "BOFU" in n_upper else "ADS_CAMPAIGN",
        "funnel_stage": "BOFU" if "BOFU" in n_upper else "GENERAL",
    }


