        f"7d `{w_ga4.get('active_users', 0)}`u (`{w_ga4.get('high_intent_views', 0)}` HI) | "
        f"30d `{m_ga4.get('active_users', 0)}`u (`{m_ga4.get('high_intent_views', 0)}` HI) | "
        f"All-Time `{all_ga4.get('active_users', 0)}`u"
