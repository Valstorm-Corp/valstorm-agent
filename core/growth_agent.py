async def run_growth_react_review(
    ads_data: Dict[str, Any],
    ga4_data: Dict[str, Any],
    gsc_data: Dict[str, Any],
    instantly_data: Dict[str, Any],
    meta_data: Optional[Dict[str, Any]] = None,
    api_key: Optional[str] = None,
    max_iterations: int = 12,
    monorepo_root: Optional[Path] = None,
) -> GrowthAgentReviewResult:
    """Runs a multi-turn ReAct agent investigation over Google Ads, Meta Ads, GA4, GSC, and Instantly telemetry."""
    proposals_sink: List[GrowthActionProposal] = []
    trace_sink: List[str] = []

    registry = build_growth_investigation_registry(
        ads_data=ads_data,
        ga4_data=ga4_data,
        gsc_data=gsc_data,
        instantly_data=instantly_data,
        proposals_sink=proposals_sink,
        trace_sink=trace_sink,
        meta_data=meta_data,
        monorepo_root=monorepo_root,
    )

    gemini_key = (
        api_key
        or os.getenv("GEMINI_API_KEY")
        or os.getenv("GOOGLE_API_KEY")
        or KeyStore.resolve_key("gemini", override_key=api_key)
    )

    baseline = build_deterministic_growth_review(
        ads_data=ads_data,
        ga4_data=ga4_data,
        gsc_data=gsc_data,
        instantly_data=instantly_data,
        meta_data=meta_data,
    )

    if not gemini_key:
        logger.info("No GEMINI_API_KEY/GOOGLE_API_KEY configured; returning deterministic growth review.")
        return baseline

    try:
        from providers.gemini import GeminiProvider

        model_name = os.getenv("GEMINI_MODEL", "gemini-flash-latest")
        backend = "aistudio" if gemini_key.startswith("AIza") else None
        provider = GeminiProvider(api_key=gemini_key, default_model=model_name, backend=backend)
        engine = ReActEngine(provider=provider, tools=registry)

        system_prompt = (
            "You are the Valstorm Autonomous Growth & RevOps Strategist Agent running inside Kubernetes.\n"
            "Your job is to review Jared's multi-horizon marketing telemetry across two primary verticals:\n"
            "1. Enterprise Greenfield / Custom Software ($25k-$40k sprints)\n"
            "2. CT Local General Services & CT Contractors/Trades RevOps (0.8s Astro speed rebuilds, Google/Meta Ads audit, missed-call SMS text-back)\n\n"
            "Operating Protocol (ReAct Loop):\n"
            "1. Call `inspect_ads_campaigns_and_horizons`, `inspect_meta_ads_campaigns_and_audiences`, "
            "`inspect_ads_search_terms_and_waste`, `inspect_ga4_funnel_and_pages`, and `inspect_instantly_outbound` "
            "(call them once each — do not repeat identical tool calls).\n"
            "2. Correlate Google Ads & Meta Ads status/spend with GA4 landing page engagement (`/book-architecture-audit`, `/ad-conversion-audit`, `/ad-conversion-audit/contractors`) and Instantly outbound reply rates. "
            "Note: if Meta Ads campaigns are PAUSED with $0.00 spend and 0 impressions while GA4 shows `meta / paid_social` hits, recognize that those GA4 sessions are Meta Ad Review pre-flight crawlers triggered when the 10 ads were provisioned!\n"
            "3. Register 3 to 4 concrete, high-ROI recommendations using `propose_growth_action` (with IDs A1, A2, A3, A4).\n"
            "4. Immediately after registering proposals, conclude with a concise, high-signal Markdown briefing summarizing:\n"
            "   - What happened Yesterday vs 7d vs 30d vs All-Time across Google Ads, Meta Ads, GA4, and Instantly\n"
            "   - Vertical performance & launch readiness (Enterprise Greenfield vs CT Local/Contractors)\n"
            "   - Key bottlenecks & how your proposed actions [A1..An] fix them."
        )

        session = SessionState(
            session_id=f"growth_review_{datetime.now(timezone.utc).strftime('%Y%m%d_%H%M%S')}",
            active_model=model_name,
        )
        session.add_message(Message(role="system", content=system_prompt))

        user_prompt = (
            "Execute today's multi-horizon marketing & outbound telemetry investigation now. "
            "Inspect Google Ads, Meta Ads (campaigns, adsets, ads, and audiences), GA4 ranged funnel metrics, "
            "and Instantly outbound angles, register your top action proposals via `propose_growth_action`, "
            "and provide your executive review."
        )

        final_msg = await engine.run_turn(
            session=session,
            user_input=user_prompt,
            model=model_name,
            max_iterations=max_iterations,
        )

        agent_text = (final_msg.content or "").strip()
        if "Terminated after reaching maximum iterations" in agent_text:
            agent_text = ""

        enriched = build_deterministic_growth_review(
            ads_data=ads_data,
            ga4_data=ga4_data,
            gsc_data=gsc_data,
            instantly_data=instantly_data,
            meta_data=meta_data,
            existing_proposals=proposals_sink if proposals_sink else None,
            tool_trace=trace_sink if trace_sink else ["react_turn_completed"],
        )
        if agent_text:
            enriched.raw_agent_markdown = agent_text
        return enriched
    except Exception as e:
        logger.warning(f"ReAct growth review encountered error ({e}); using deterministic review with captured proposals.")
        return build_deterministic_growth_review(
            ads_data=ads_data,
            ga4_data=ga4_data,
            gsc_data=gsc_data,
            instantly_data=instantly_data,
            meta_data=meta_data,
            existing_proposals=proposals_sink if proposals_sink else None,
            tool_trace=trace_sink if trace_sink else None,
        )


async def answer_growth_slack_question(
    question: str,
    cached_snapshot: Dict[str, Any],
    api_key: Optional[str] = None,
) -> str:
    """Runs an on-demand ReAct turn when Jared replies to a #marketing thread with a question."""
    ads_data = cached_snapshot.get("ads", {})
    meta_data = cached_snapshot.get("meta", {})
    ga4_data = cached_snapshot.get("ga4", {})
    gsc_data = cached_snapshot.get("gsc", {})
    instantly_data = cached_snapshot.get("instantly", {})

    proposals_sink: List[GrowthActionProposal] = []
    trace_sink: List[str] = []

    registry = build_growth_investigation_registry(
        ads_data=ads_data,
        ga4_data=ga4_data,
        gsc_data=gsc_data,
        instantly_data=instantly_data,
        proposals_sink=proposals_sink,
        trace_sink=trace_sink,
        meta_data=meta_data,
    )

    gemini_key = (
        api_key
        or os.getenv("GEMINI_API_KEY")
        or os.getenv("GOOGLE_API_KEY")
        or KeyStore.resolve_key("gemini", override_key=api_key)
    )
    if not gemini_key:
        review = build_deterministic_growth_review(ads_data, ga4_data, gsc_data, instantly_data, meta_data=meta_data)
        return (
            f"*(Deterministic Mode — `GEMINI_API_KEY` not set)*\n"
            f"{review.executive_headline}\n\n{review.ranged_pulse_summary}"
        )

    try:
        from providers.gemini import GeminiProvider

        model_name = os.getenv("GEMINI_MODEL", "gemini-flash-latest")
        backend = "aistudio" if gemini_key.startswith("AIza") else None
        provider = GeminiProvider(api_key=gemini_key, default_model=model_name, backend=backend)
        engine = ReActEngine(provider=provider, tools=registry)

        session = SessionState(
            session_id=f"growth_qa_{int(datetime.now(timezone.utc).timestamp())}",
            active_model=model_name,
        )
        session.add_message(
            Message(
                role="system",
                content=(
                    "You are the Valstorm Growth & Telemetry ReAct Agent replying in a Slack thread. "
                    "Use your inspection tools (Google Ads, Meta Ads, GA4, Instantly) to check the exact numbers "
                    "across Yesterday, 7d, 30d, and All-Time and answer the user's question concisely with Slack mrkdwn formatting."
                ),
            )
        )
        msg = await engine.run_turn(
            session=session,
            user_input=question,
            model=model_name,
            max_iterations=6,
        )
        return (msg.content or "Completed inspection, no additional output.").strip()
    except Exception as e:
        logger.error(f"Error answering growth Slack question: {e}")
        return f"⚠️ Failed to run growth ReAct query: `{e}`"


def format_growth_review_slack_blocks(review: GrowthAgentReviewResult) -> List[Dict[str, Any]]:
    """Formats the ReAct Growth Agent's review & action proposals into Slack Block Kit blocks for thread reply."""
    blocks: List[Dict[str, Any]] = [
        {
            "type": "header",
            "text": {
                "type": "plain_text",
                "text": "🧠 Autonomous Growth Agent Review (ReAct Triage)",
                "emoji": True,
            },
        },
        {
            "type": "section",
            "text": {
                "type": "mrkdwn",
                "text": f"*Executive Takeaway:*\n{review.executive_headline}",
            },
        },
    ]

    if review.anomalies_and_bottlenecks:
        bullet_text = "\n".join(f"• {b}" for b in review.anomalies_and_bottlenecks[:5])
        blocks.append(
            {
                "type": "section",
                "text": {
                    "type": "mrkdwn",
                    "text": f"*🔍 Key Bottlenecks & Anomalies Detected:*\n{bullet_text}"[:2950],
                },
            }
        )

    if review.proposals:
        blocks.append({"type": "divider"})
        prop_lines = []
        for p in review.proposals[:5]:
            prop_lines.append(
                f"*`[{p.action_id}]` ({p.priority} • {p.vertical}): {p.title}*\n"
                f"↳ _Why:_ {p.rationale}\n"
                f"↳ _Action:_ {p.suggested_execution}"
            )
        blocks.append(
            {
                "type": "section",
                "text": {
                    "type": "mrkdwn",
                    "text": ("*🚀 Recommended Actions:*\n\n" + "\n\n".join(prop_lines))[:2950],
                },
            }
        )

    tools_used = ", ".join(f"`{t.split('(')[0]}`" for t in review.tool_trace[:6]) if review.tool_trace else "`baseline`"
    blocks.append(
        {
            "type": "context",
            "elements": [
                {
                    "type": "mrkdwn",
                    "text": (
                        f"🔧 *ReAct Tools Used:* {tools_used}\n"
                        f"💡 *Reply in thread:* `@Valstorm Bot create ticket A1` to log an action item, or `@Valstorm Bot <question>` to drill deeper."
                    ),
                }
            ],
        }
    )
    return blocks
