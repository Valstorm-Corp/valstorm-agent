def classify_instantly_campaign(name: str) -> Dict[str, str]:
    """Extracts a clean angle code and vertical from an Instantly campaign name (never blindly returns OTHER)."""
    cname = (name or "").strip()
    c_upper = cname.upper()

    # 1. Known Enterprise Sprint angles
    enterprise_angles = {
        "HIRE_ARB": "Enterprise Greenfield",
        "RETOOL_ESC": "Enterprise Greenfield",
        "VELOCITY_LAG": "Enterprise Greenfield",
        "ENG_OFFLOAD": "Enterprise Greenfield",
        "AGENCY_ALT": "Enterprise Greenfield",
    }
    for code, vert in enterprise_angles.items():
        if code in c_upper:
            return {"angle": code, "vertical": vert}

    # 2. CT Trades / Local Services / RevOps angles
    if "CT TRADES" in c_upper or "CT LOCAL" in c_upper or "CONTRACTOR" in c_upper or "REVOPS" in c_upper:
        vertical = "CT Contractors & Trades" if "TRADES" in c_upper or "CONTRACTOR" in c_upper else "CT Local General Services"
        tier_match = re.search(r"TIER\s*([0-9]+[A-Z]?)", c_upper)
        if tier_match:
            tier_code = tier_match.group(1)
            return {"angle": f"CT_TIER_{tier_code}", "vertical": vertical}
        if "BLEEDING ON ADS" in c_upper:
            return {"angle": "CT_ADS_BLEED", "vertical": vertical}
        if "NO WEBSITE" in c_upper:
            return {"angle": "CT_NO_SITE", "vertical": vertical}
        if "SLOW MOBILE" in c_upper:
            return {"angle": "CT_SLOW_MOBILE", "vertical": vertical}
        if "REVOPS" in c_upper or "TRACKING" in c_upper:
            return {"angle": "CT_REVOPS_GAP", "vertical": vertical}
        return {"angle": "CT_OUTBOUND", "vertical": vertical}

    # 3. Extract bracketed tag or clean slug fallback
    bracket_tags = re.findall(r"\[([^\]]+)\]", cname)
    if bracket_tags:
        last_tag = re.sub(r"[^A-Za-z0-9]+", "_", bracket_tags[-1]).strip("_").upper()
        if last_tag and last_tag not in ("VALSTORM", "SPRINT"):
            return {"angle": last_tag[:16], "vertical": "Custom Outbound"}

    slug = re.sub(r"[^A-Za-z0-9]+", "_", cname).strip("_").upper()
    return {"angle": (slug[:16] if slug else "OUTBOUND"), "vertical": "General Outbound"}


def classify_ga4_page_vertical(page_path: str) -> Dict[str, Any]:
    """Maps a GA4 pagePath to its commercial intent tier and vertical."""
    p = (page_path or "/").lower()
    if "/ad-conversion-audit/contractors" in p or "contractor" in p:
        return {
            "vertical": "CT Contractors & Trades",
            "is_high_intent": True,
            "intent_label": "🔥 CT Contractors BOFU",
        }
    if "/ad-conversion-audit" in p or "/ct-" in p:
        return {
            "vertical": "CT Local General Services",
            "is_high_intent": True,
            "intent_label": "🔥 CT Local Audit BOFU",
        }
    if any(k in p for k in ["book-architecture-audit", "pricing", "greenfield", "custom-internal-tools", "enterprise-ai", "audit"]):
        return {
            "vertical": "Enterprise Greenfield",
            "is_high_intent": True,
            "intent_label": "🔥 Enterprise BOFU",
        }
    return {
        "vertical": "Brand / Core Web",
        "is_high_intent": False,
        "intent_label": "Info / Brand",
    }


def select_primary_ads_campaign(campaigns: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Selects the primary active BOFU summary without letting paused $0 campaigns overwrite enabled ones."""
    if not campaigns:
        return {
            "id": "none",
            "name": "No Campaigns Configured",
            "status": "NONE",
            "cost_usd": 0.0,
            "clicks": 0,
            "impressions": 0,
            "ctr_pct": 0.0,
            "avg_cpc_usd": 0.0,
            "conversions": 0.0,
        }

    enabled = [c for c in campaigns if str(c.get("status", "")).upper() in ("ENABLED", "ACTIVE")]
    pool = enabled if enabled else campaigns
    ranked = sorted(
        pool,
        key=lambda c: (
            1 if str(c.get("status", "")).upper() in ("ENABLED", "ACTIVE") else 0,
            float(c.get("cost_usd", 0.0)),
            int(c.get("clicks", 0)),
        ),
        reverse=True,
    )
    primary = dict(ranked[0])
    primary["active_campaigns_count"] = len(enabled)
    primary["paused_campaigns_count"] = len(campaigns) - len(enabled)
    primary["total_campaigns_count"] = len(campaigns)
    return primary


